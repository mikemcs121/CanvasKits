const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../..'),{Resvg}=require(path.join(root,'assets/tools/vector-tools/node_modules/@resvg/resvg-js'));
const g=JSON.parse(fs.readFileSync(path.join(root,'Owl/info/assets/geometry.json')));
const ids=new Set([139,153,197,260,277,344,376,398]);
const removed=g.centerlinePaths.filter((_,i)=>ids.has(i));
fs.writeFileSync(path.join(__dirname,'before-geometry.json'),JSON.stringify(g,null,2));
const body=g.centerlinePaths.map((d,i)=>`<path d="${d}" stroke="${ids.has(i)?'#e00060':'#808080'}"/>`).join('');
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="600" viewBox="0 1180 1024 384"><rect x="0" y="1180" width="1024" height="384" fill="white"/><g fill="none" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>`;
fs.writeFileSync(path.join(__dirname,'removed-lines.png'),new Resvg(svg).render().asPng());
fs.writeFileSync(path.join(__dirname,'removed-paths.json'),JSON.stringify(removed,null,2));
g.centerlinePaths=g.centerlinePaths.filter((_,i)=>!ids.has(i));
g.omittedCenterlinePaths=[...(g.omittedCenterlinePaths||[]),...removed];
fs.writeFileSync(path.join(__dirname,'geometry.json'),JSON.stringify(g,null,2));
console.log('Prepared removal of '+removed.length+' woodgrain paths.');
