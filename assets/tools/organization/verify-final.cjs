// Historical: audited the September 20 organization. Later work (Tools/, simplified/, root assets/) and the
// September 25 info/ cleanup mean it no longer passes; use assets/tools/reference-restoration/verify-completed.cjs.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'../../..');
const read=p=>fs.readFileSync(path.join(root,p));
const json=p=>JSON.parse(read(p).toString('utf8').replace(/^\uFEFF/,''));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex').toUpperCase();
const assert=(v,s)=>{if(!v)throw Error(s)};
const kits=json('assets/tools/organization/selections.json'),result=[];
const allowedDirectories=new Set([...kits.map(k=>k.folder),'.agents','.git','.hivemind','assets'].map(n=>n.toLowerCase()));
for(const entry of fs.readdirSync(root,{withFileTypes:true}))if(entry.isDirectory())assert(allowedDirectories.has(entry.name.toLowerCase()),'Unexpected project directory: '+entry.name);
const originalTransfers=json('Fox Fall/info/tmp/darker-outline/verification.json');
for(const k of kits){
 const entries=fs.readdirSync(path.join(root,k.folder),{withFileTypes:true});
 assert(entries.filter(e=>e.isFile()).length===3,k.folder+' root file count');
 assert(entries.filter(e=>e.isDirectory()).map(e=>e.name).join()==='info',k.folder+' directories');
 const selections=json(k.folder+'/info/production-selection.json');
 for(const f of selections)assert(sha(fs.readFileSync(f.destination))===f.sha256,k.folder+' selected hash '+f.role);
 const svg=read(k.folder+'/'+k.slug+'-outline-8x10.svg').toString();
 const original=originalTransfers.find(r=>r.kit.toLowerCase()===k.folder.toLowerCase());
 let transferUnchanged=original&&sha(Buffer.from(svg))===original.svgSha256.toUpperCase();
 if(!transferUnchanged&&original&&k.slug==='cat-in-pumpkin'){
  const backup=read(k.folder+'/info/archive/name-correction-original-text/'+original.svgSha256.toUpperCase()+'.gz');
  const prior=require('zlib').gunzipSync(backup);
  const withoutTitle=s=>s.replace(/<title>[\s\S]*?<\/title>/,'');
  transferUnchanged=sha(prior)===original.svgSha256.toUpperCase()&&withoutTitle(prior.toString())===withoutTitle(svg);
 }
 assert(transferUnchanged,k.folder+' original production SVG geometry/style unchanged');
 assert(/width="8in"/.test(svg)&&/height="10in"/.test(svg),k.folder+' SVG physical size');
 assert(!/<(?:image|rect|filter|mask)\b/.test(svg)&&!svg.includes('data:image')&&svg.includes('<path'),k.folder+' vector transparency');
 const vb=svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
 const weight=Number(svg.match(/stroke-width="([^"]+)"/)[1])*576/vb[2];
 assert(Math.abs(weight-2)<1e-6,k.folder+' line weight');
 const color=['fox-fall','cat-in-pumpkin'].includes(k.slug)?'#808080':'#A6A6A6';
 assert(svg.includes('stroke="'+color+'"'),k.folder+' gray');
 for(const [role,suffix,w,h] of [['guide','painting-guide',612,792],['reference','finished-reference',576,720]]){
  const pdf=read(k.folder+'/'+k.slug+'-'+suffix+'-8x10.pdf').toString('latin1');
  assert((pdf.match(/\/Type\s*\/Page\b/g)||[]).length===1,k.folder+' '+role+' pages');
  const boxes=[...pdf.matchAll(/\/MediaBox\s*\[([^\]]+)\]/g)].map(m=>m[1].trim().split(/\s+/).map(Number));
  assert(boxes.length===1&&boxes[0].join()===`0,0,${w},${h}`,k.folder+' '+role+' size');
 }
 const preserved=json(k.folder+'/info/organization-manifest.json');
 // Browser session/telemetry caches are regenerated by subsequent PDF exports;
 // source artwork, build sources, and deliverables remain preservation checks.
 const volatileCache=r=>/[/\\]chrome-organization[/\\](?:CrashpadMetrics\.pma|Default[/\\]Sessions[/\\](?:Session_|Tabs_))/.test(r.new);
 for(const r of preserved)assert(fs.existsSync(path.join(root,r.new))||volatileCache(r),k.folder+' missing preserved file '+r.new);
 result.push({kit:k.folder,rootFiles:entries.filter(e=>e.isFile()).map(e=>e.name),svgGray:color,linePoints:weight,pdfChecks:true,preservedFiles:preserved.length,productionHashesVerified:true});
}
assert(!fs.existsSync(path.join(root,'Starry Night Sunflower')),'Duplicate Sunflower folder remains');
const extra=json('Starry-night Sunflower/info/sunflower-consolidation-manifest.json');
for(const r of extra)assert(sha(read(r.new))===r.sha256,'Sunflower preservation '+r.new);
for(const p of ['canvas-kits.md','canvas-transfer-outlines.md','new-autumn-kits-8x10.md']){
 const s=read(p).toString();
 for(const m of s.matchAll(/\]\((?:<([^>]+)>|([^\)]+))\)/g)){const target=m[1]||m[2];if(!target.includes('://'))assert(fs.existsSync(path.join(root,target)),p+' broken link '+target)}
}
fs.writeFileSync(path.join(__dirname,'final-checks.json'),JSON.stringify({kits:result,sunflowerArchivedFiles:extra.length,localIndexLinksValid:true},null,2));
console.log('Verified all 10 roots, 30 production files, SVG standards/hashes, PDF pages/sizes, preserved paths, Sunflower consolidation and index links.');
